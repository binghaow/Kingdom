/* P4 4a: the one command interface of the simulation (players, computer players, replays, the simulation worker).

   A command is plain JSON:  { type, team, args }
     type  one of TYPES - the player-facing entry points of the Sim (order, construct, train, research incl. age-up, rally,
           ships, hero skills, rewards, ...). Same names the P1 replay recorder captures ({m, a} in recordings and worker
           messages is the same command with m = type and no team).
     team  the seat that issues it. Computer commands always carry it and are validated against it (a seat can only command
           its own units and buildings); player commands from the UI / a recording carry none (the UI only offers own units).
     args  the call arguments, encoded with encodeArg: a live unit / building / resource node becomes {$e: id}.

   Computer players: the AI runs inside the simulation step in an "AI phase" (sim.aiScope). In that phase every entry point
   below does NOT run; it is encoded into a command and appended to the simulation's command queue (sim.s.commandQueue, part of
   the saved and synced state). The AI gets a dry-run answer at once (the same error check the entry point would make, e.g.
   placement / cost / prerequisites), so its "try another spot" loops keep working. The queue is applied first thing in the
   next step (drainCommands), through applyCommand - the same function the replay runner and the worker use for player commands.
   Online computer seats behave the same on every peer (the queue is simulation state). Online human commands keep their own
   network rules (public/network-commands.js: visibility, limits) and then call the same entry points.

   Environment-free (no DOM, no clock). Bundled into public/kingdom-core.js and public/sim-worker.js through the src/ imports,
   and into public/kingdom-commands.js (UMD, generated by scripts/build-core.cjs) for the classic simulation scripts. */

export const FORMAT = 'kingdom-command', VERSION = 1;

/* The player-facing entry points (= replay CAPTURED list, unchanged order: recordings index by name, not position). */
export const TYPES = ['order', 'construct', 'constructLine', 'train', 'research', 'setRally', 'board', 'unload', 'assignFish',
  'skill', 'castSpell', 'route', 'claimReward', 'setDifficulty', 'sendChat', 'pact', 'add',
  'offerAlliance', 'acceptAlliance', 'rejectAlliance', 'declareWar'];

/* Entry points a computer seat may issue. Anything else called in the AI phase is a bug (thrown, so checks catch it). */
export const AI_TYPES = ['order', 'construct', 'constructLine', 'train', 'research', 'setRally', 'board', 'unload', 'assignFish',
  'skill', 'castSpell', 'route', 'claimReward'];

const isEntity = (sim, v) => typeof v.id === 'number' && typeof sim.byId === 'function' && sim.byId(v.id) === v;

export function encodeArg(sim, v, depth = 0) {
  if (v === undefined) return { $u: 1 };
  if (v === null || typeof v === 'string' || typeof v === 'boolean') return v;
  if (typeof v === 'number') return Number.isFinite(v) ? v : { $n: String(v) };
  if (typeof v === 'function') return { $u: 1 };
  if (depth > 6) throw Error('command: argument nested too deeply');
  if (Array.isArray(v)) return v.map((x) => encodeArg(sim, x, depth + 1));
  if (typeof v === 'object') {
    if (isEntity(sim, v)) return { $e: v.id };
    const out = {};
    for (const k of Object.keys(v)) { if (typeof v[k] !== 'function') out[k] = encodeArg(sim, v[k], depth + 1); }
    return out;
  }
  return null;
}
export function decodeArg(sim, v) {
  if (v === null || typeof v !== 'object') return v;
  if (Array.isArray(v)) return v.map((x) => decodeArg(sim, x));
  if ('$u' in v) return undefined;
  if ('$n' in v) return Number(v.$n);
  if ('$e' in v) return sim.byId(v.$e) ?? { id: v.$e, missing: true };
  const out = {};
  for (const k of Object.keys(v)) out[k] = decodeArg(sim, v[k]);
  return out;
}
/* What a command returned (toast text, the new building, an {error}) - stored by recordings / worker replies. */
export const resultOf = (r) => {
  if (r === undefined || r === null || typeof r === 'string' || typeof r === 'boolean' || typeof r === 'number') return r ?? null;
  if (typeof r.id === 'number') return { $e: r.id };
  if (typeof r.error === 'string') return { error: r.error };
  if (r.building && typeof r.building.id === 'number') return { building: r.building.id };
  return '[object]';
};

const alive = (e) => e && !e.missing && e.hp > 0;
/* Which argument holds the acting entity (or entity list) / the team, per type. */
const ACTOR = {
  order: (a) => ({ units: a[0] }), construct: (a) => ({ units: a[3], team: a[4] ?? 0 }), constructLine: (a) => ({ units: a[3], team: a[4] ?? 0 }),
  train: (a) => ({ entity: a[0] }), research: (a) => ({ entity: a[0] }), setRally: (a) => ({ entity: a[0] }),
  board: (a) => ({ entity: a[0] }), unload: (a) => ({ entity: a[0] }), assignFish: (a) => ({ entity: a[0] }),
  skill: (a) => ({ entity: a[0] }), castSpell: (a) => ({ entity: a[0] }), route: (a) => ({ entity: a[0] }),
  claimReward: (a) => ({ team: a[0] }),
};
/* The seat a call acts for (computer commands are stamped with it). null when the type has no actor. */
export function teamOf(type, args) {
  const f = ACTOR[type]; if (!f) return null;
  const x = f(args);
  if (x.team !== undefined) return x.team;
  if (x.entity) return x.entity.team;
  if (Array.isArray(x.units)) { const u = x.units.find((u) => u && typeof u === 'object'); return u ? u.team : null; }
  return null;
}

/* Validation of a decoded command for a seat. Returns '' or a reason. Ownership: a seat only commands its own living units and
   buildings (order / construct keep only those units, like a selection that lost some members). */
export function check(sim, type, team, args) {
  if (!TYPES.includes(type)) return 'unknown command ' + type;
  if (team === null || team === undefined) return '';
  const f = ACTOR[type]; if (!f) return '';
  const x = f(args);
  if (x.team !== undefined && x.team !== team) return 'wrong seat';
  if (x.entity !== undefined && (!alive(x.entity) || x.entity.team !== team)) return 'actor gone or not owned';
  if (x.units !== undefined) {
    if (!Array.isArray(x.units)) return 'no units';
    const own = x.units.filter((u) => alive(u) && u.team === team);
    if (!own.length) return 'units gone or not owned';
  }
  return '';
}
/* Same arguments with the unit list trimmed to the seat's living units. */
function owned(type, team, args) {
  if (team === null || team === undefined) return args;
  const i = type === 'order' ? 0 : (type === 'construct' || type === 'constructLine') ? 3 : -1;
  if (i < 0 || !Array.isArray(args[i])) return args;
  const out = args.slice(); out[i] = args[i].filter((u) => alive(u) && u.team === team);
  return out;
}

/* The answer a computer seat gets at once in the AI phase (the command itself runs next step): {ok, result}. `result` mirrors
   what the entry point would return on the same checks (placement / cost / prerequisites / ownership), so "if this spot fails
   try the next one" loops behave as before; ok = false means nothing is queued. */
export function dryRun(sim, type, team, args) {
  const err = check(sim, type, team, args);
  let e = err;
  switch (type) {
    case 'construct': {
      if (!e) {
        const [kind, x, y, workers] = args;
        if (!workers.some((u) => (sim.builder ? sim.builder(u) : u.kind === 'villager') && u.team === team)) e = '先选择村民';
        else e = sim.placementError(kind, x, y, team);
      }
      return e ? { ok: false, result: { error: e } } : { ok: true, result: { queued: true } };
    }
    case 'constructLine': return e ? { ok: false, result: { count: 0, error: e, planned: 0 } } : { ok: true, result: { count: 0, error: '', planned: 0, queued: true } };
    case 'train': e = e || (sim.unitError ? sim.unitError(args[0], args[1]) : '') || ''; return { ok: !e, result: e };
    case 'research': e = e || (sim.researchError ? sim.researchError(args[0], args[1]) : '') || ''; return { ok: !e, result: e };
    case 'skill': e = e || (sim.skillError ? sim.skillError(args[0]) : '') || ''; return { ok: !e, result: e };
    case 'order': case 'assignFish': return { ok: !e, result: undefined };
    default: return { ok: !e, result: e };
  }
}

/* Make a queued command (AI phase). */
export function make(sim, type, team, args) {
  return { type, team, args: args.map((a) => encodeArg(sim, a)) };
}

/* Apply one command: decode, validate for its seat, call the entry point. `call(name, args)` runs the real entry point
   (the simulation passes one that bypasses its AI-phase gate). Returns the entry point's result or {error}. */
export function applyCommand(sim, cmd, call = (name, args) => sim[name](...args)) {
  const type = cmd.type ?? cmd.m, team = cmd.team ?? null;
  if (!TYPES.includes(type)) return { error: 'unknown command ' + type };
  let args = (cmd.args ?? cmd.a ?? []).map((a) => decodeArg(sim, a));
  const err = check(sim, type, team, args);
  if (err) return { error: err };
  args = owned(type, team, args);
  return call(type, args);
}

/* Apply and empty the queue (start of a step). Returns how many ran. */
export function drainCommands(sim, call) {
  const s = sim.s, q = s.commandQueue;
  if (!q || !q.length) return 0;
  s.commandQueue = [];
  for (const c of q) {
    const r = applyCommand(sim, c, call);
    if (sim.commandStats) { sim.commandStats.applied++; if (r && typeof r === 'object' && r.error) sim.commandStats.rejected++; }
  }
  return q.length;
}
