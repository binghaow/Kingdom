#!/usr/bin/env python3
"""Offline builder for the modular stone wall / gate sprites (walls-v1.png + walls-v1.json).

Every pixel is derived from artwork that is already in the repository; nothing is generated by a model:
  * public/assets/industry-v2.png cell 10 (stone curtain wall): perspective-rectified, then cut into a
    seamlessly repeating wall face (masonry, corbel band, parapet, merlons) and stone top surfaces.
  * public/assets/industry-v2.png cell 11 (stone gatehouse): central arch, doors (open), lanterns, corbels.
  * public/assets/industry-v2.png cell 13 (palisade gate): the closed timber double doors.
  * public/assets/industry-v2.png cell 10 banner, with the fleur-de-lis painted out (plain cloth, recoloured
    to the team colour at runtime).

The sprites follow the in-game wall projection used by wall-art.js / fortification.js: the ground plane is
the simulation plane (x right, y down) and a point at height z is drawn at (x, y - z). Wall footprints are
unchanged: horizontal segment 96 x 24, vertical 24 x 96, junction tower 30 x 30, gate 96 x 28 / 28 x 96.

Usage: python3 scripts/art/build_walls.py [repo_root]
Requires Pillow and numpy only.
"""
import json, os, sys
import numpy as np
from PIL import Image, ImageFilter

ROOT = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), '..', '..'))
ASSETS = os.path.join(ROOT, 'public', 'assets')
S = 2                      # sprite pixels per game pixel
SEG = 96                   # segment length (game px)
P_R = 411                  # one segment in rectified-wall pixels (3 merlon periods)
K = SEG / P_R              # game px per rectified px
F = S * K                  # sprite px per rectified px
# heights (game px)
Z_WALK, Z_SILL, Z_TOP = 88, 96, 111           # wall walkway, parapet sill, merlon top
T_WALK, T_SILL, T_TOP = 98, 106, 121          # junction tower
G_WALK, G_SILL, G_TOP = 104, 112, 124         # gatehouse
PAR = 5                                        # parapet thickness
MER = 18                                       # merlon length, period 32 (merlon centres at x = 16 mod 32)
SHADOW = (0.30, 0.12, 0.36)                    # ground shadow direction per unit height, opacity


# ---------------------------------------------------------------- sources
def atlas_cell(i):
    im = Image.open(os.path.join(ASSETS, 'industry-v2.png')).convert('RGBA')
    cw, ch = im.width / 4, im.height / 4
    return im.crop((int((i % 4) * cw), int((i // 4) * ch), int((i % 4 + 1) * cw), int((i // 4 + 1) * ch)))


def homography(src, dst):
    a, b = [], []
    for (x, y), (u, v) in zip(src, dst):
        a += [[x, y, 1, 0, 0, 0, -u * x, -u * y], [0, 0, 0, x, y, 1, -v * x, -v * y]]
        b += [u, v]
    h = np.linalg.solve(np.array(a, float), np.array(b, float))
    return np.append(h, 1).reshape(3, 3)


def rectified_wall():
    """Perspective-rectify the receding curtain wall of cell 10 into a frontal elevation (990 px wide)."""
    cell = atlas_cell(10)
    W, top, H = 990, 160, 363
    quad = [(48, 113), (330, 63), (330, 166), (48, 234)]          # corbel line and wall foot, both ends
    h = homography([(0, top), (W, top), (W, top + H), (0, top + H)], quad)
    return cell.transform((W, top + H + 60), Image.PERSPECTIVE, h.flatten()[:8], Image.BICUBIC)


def arr(im):
    return np.asarray(im.convert('RGBA'), dtype=np.float32) / 255.0


def img(a):
    return Image.fromarray(np.clip(a * 255 + .5, 0, 255).astype(np.uint8), 'RGBA')


def periodic(c, period, overlap):
    """Make a crop of width period+overlap horizontally periodic with a minimum-error seam (image quilting)."""
    a, b = c[:, period:period + overlap], c[:, :overlap]
    err = (np.abs(a[..., :3] * a[..., 3:] - b[..., :3] * b[..., 3:]).sum(2) + np.abs(a[..., 3] - b[..., 3]))
    h = err.shape[0]
    cost = err.copy()
    for y in range(1, h):
        prev = cost[y - 1]
        best = np.minimum(prev, np.minimum(np.r_[np.inf, prev[:-1]], np.r_[prev[1:], np.inf]))
        cost[y] += best
    cut = np.zeros(h, int)
    cut[-1] = int(np.argmin(cost[-1]))
    for y in range(h - 2, -1, -1):
        x = cut[y + 1]
        lo, hi = max(0, x - 1), min(overlap, x + 2)
        cut[y] = lo + int(np.argmin(cost[y, lo:hi]))
    out = c[:, :period].copy()
    xs = np.arange(overlap)
    for y in range(h):
        w = np.clip((xs - cut[y] + 2) / 4.0, 0, 1)[:, None]            # 4 px feather across the seam
        out[y, :overlap] = a[y] * (1 - w) + b[y] * w
    return out


def resize(a, w, h):
    """Premultiplied-alpha Lanczos resize (no dark/white fringes)."""
    pm = a.copy()
    pm[..., :3] *= pm[..., 3:]
    chans = [np.asarray(Image.fromarray(pm[..., i]).resize((w, h), Image.LANCZOS)) for i in range(4)]
    out = np.clip(np.stack(chans, 2), 0, 1)
    al = out[..., 3:]
    out[..., :3] = np.where(al > 1e-4, out[..., :3] / np.maximum(al, 1e-4), 0)
    return np.clip(out, 0, 1)


def sharpen(a, amount=0.45):
    rgb = img(a).convert('RGB').filter(ImageFilter.UnsharpMask(radius=1.2, percent=int(amount * 100), threshold=2))
    out = a.copy()
    out[..., :3] = np.asarray(rgb, np.float32) / 255
    return out


def grade(a, mul=1.0, sat=1.0, add=0.0):
    out = a.copy()
    g = out[..., :3].mean(2, keepdims=True)
    out[..., :3] = np.clip((g + (out[..., :3] - g) * sat) * mul + add, 0, 1)
    return out


# ---------------------------------------------------------------- textures
def build_textures():
    R = arr(rectified_wall())
    x0 = 385                                                         # window centred on a banner-free buttress
    bands = periodic(R[98:506, x0:x0 + P_R + 44], P_R, 44)            # parapet, corbels, masonry, plinth
    face = np.zeros((506 - 30, P_R, 4), np.float32)
    face[98 - 30:] = bands
    face[:98 - 30 + 2] *= 0                                           # above the sill: transparent except merlons
    face[98 - 30:98 - 30 + 2] = bands[:2]
    merlon = R[33:101, 425:503].copy()                               # one merlon: lit cap, front, shaded flank
    period = P_R / 3
    for k in range(4):                                               # merlon centres at tile u = 0, 32, 64, 96 game px
        cx = int(round(k * period)) - merlon.shape[1] // 2
        for dx in range(merlon.shape[1]):
            x = cx + dx
            if 0 <= x < P_R:
                col = merlon[:, dx]
                dst = face[:col.shape[0], x]
                al = col[:, 3:]
                dst[:] = np.concatenate(
                    [col[:, :3] * al + dst[:, :3] * dst[:, 3:] * (1 - al), al + dst[:, 3:] * (1 - al)], 1)
                m = dst[:, 3:] > 1e-4
                dst[:, :3] = np.where(m, dst[:, :3] / np.maximum(dst[:, 3:], 1e-4), 0)
    rows = int(round(face.shape[0] * F))
    FACE = sharpen(resize(face, SEG * S, rows))
    # base: the source wall foot sits in weeds and soil; fade the lowest 3 px into a contact shadow instead.
    FACE = FACE[:Z_TOP * S]
    # stone top surfaces: parapet-band masonry, lighter and a little cooler (sky light from above)
    walk = periodic(R[100:162, x0:x0 + P_R + 44], P_R, 44)
    WALK = sharpen(resize(walk, SEG * S, int(round(walk.shape[0] * F))))
    TOP = grade(WALK, 1.18, .85, .02)
    WALK = grade(WALK, 1.02, .9)
    MERF = sharpen(resize(R[68:101, 437:503].copy(), int(66 * F), int(33 * F)))   # merlon front without cap
    # banner (cell 10, first buttress) with the emblem painted out
    ban = R[196:404, 238:318].copy()
    rgb = ban[..., :3]
    blue = (rgb[..., 2] > rgb[..., 0] + .06) & (ban[..., 3] > .5)
    inner = np.zeros(blue.shape, bool)
    inner[14:-30, 12:-12] = True
    fill_mask = inner & ~blue
    cloth = img(np.where(blue[..., None], ban, 0)).filter(ImageFilter.GaussianBlur(9))
    weight = Image.fromarray((blue * 255).astype(np.uint8)).filter(ImageFilter.GaussianBlur(9))
    c = np.asarray(cloth, np.float32) / 255
    wv = np.asarray(weight, np.float32)[..., None] / 255
    smooth = np.where(wv > 1e-3, c[..., :3] / np.maximum(c[..., 3:], 1e-3), rgb)
    ban[..., :3] = np.where(fill_mask[..., None], smooth, rgb)
    ban[..., 3] = np.where(fill_mask, 1.0, ban[..., 3])
    return dict(FACE=FACE, WALK=WALK, TOP=TOP, MERF=MERF, BANNER=ban)


def gate_textures(T):
    g = arr(atlas_cell(11))
    pal = arr(atlas_cell(13))
    x0, x1, y0, y1 = 127, 259, 58, 233
    # paint out the heraldic shield above the arch with neighbouring masonry (shifted copy)
    patch = g[66:116, 146:182].copy()
    g[66:116, 180:216] = patch
    open_ = g.copy()
    # through the open gateway: make the passage between the leaves transparent so the real ground shows
    yy, xx = np.mgrid[0:g.shape[0], 0:g.shape[1]]
    passage = (xx >= 181) & (xx <= 202) & (yy >= 130) & (yy <= 233)
    open_[passage, 3] = 0
    open_[(xx >= 158) & (xx < 181) & (yy >= 130) & (yy <= 146) & (open_[..., 3] < .6), 3] = 0
    # closed: the palisade gate's timber double doors set into the intrados
    closed = g.copy()
    inside = ((yy >= 160) & (yy <= 233) & (xx >= 150) & (xx <= 243)) | \
             ((((xx - 196.5) / 46.5) ** 2 + ((yy - 160) / 29.5) ** 2) <= 1)
    door = pal[127:229, 139:233]
    dh, dw = door.shape[:2]
    for y in range(130, 234):
        for x in range(150, 244):
            if inside[y, x]:
                sy = min(dh - 1, int((y - 130) / 104 * dh))
                sx = min(dw - 1, int((x - 150) / 94 * dw))
                d = door[sy, sx]
                # recess shadow: darker towards the crown and the jambs
                depth = 1 - .38 * max(0, 1 - (y - 130) / 55) - .18 * max(0, 1 - min(x - 150, 243 - x) / 9)
                closed[y, x, :3] = d[:3] * depth
                closed[y, x, 3] = 1
    out = {}
    w, h = SEG * S, int(round((y1 - y0) * SEG * S / (x1 - x0)))
    for name, a in (('GATE0', closed), ('GATE1', open_)):
        out[name] = sharpen(resize(a[y0:y1, x0:x1], w, h))
    # loose leaves for the vertical gate (cell 11 open doors)
    sc = SEG * S / (x1 - x0)
    out['LEAF_L'] = sharpen(resize(g[139:234, 152:182], int(30 * sc), int(95 * sc)))
    out['LEAF_R'] = sharpen(resize(g[132:232, 202:245], int(43 * sc), int(100 * sc)))
    out['gate_scale'] = sc / S
    return out


# ---------------------------------------------------------------- canvas
class Canvas:
    def __init__(self, x0=-72, x1=80, y0=-200, y1=72):
        self.x0, self.y0 = x0, y0
        self.a = np.zeros(((y1 - y0) * S, (x1 - x0) * S, 4), np.float32)
        self.shadow = np.zeros(self.a.shape[:2], np.float32)

    def px(self, gx, gy):
        return int(round((gx - self.x0) * S)), int(round((gy - self.y0) * S))

    def blit(self, tex, gx, gy, shade=1.0, clip=None):
        """Composite texture with its top-left at game (gx, gy). clip=(gx0,gx1) limits columns in game x."""
        if tex is None or tex.size == 0:
            return
        px, py = self.px(gx, gy)
        t = tex
        if shade != 1.0:
            t = t.copy()
            t[..., :3] = np.clip(t[..., :3] * shade, 0, 1)
        h, w = t.shape[:2]
        sx0, sy0 = max(0, -px), max(0, -py)
        ex, ey = min(w, self.a.shape[1] - px), min(h, self.a.shape[0] - py)
        if clip:
            cx0, cx1 = (clip[0] - self.x0) * S, (clip[1] - self.x0) * S
            sx0, ex = max(sx0, int(cx0 - px)), min(ex, int(cx1 - px))
        if ex <= sx0 or ey <= sy0:
            return
        src = t[sy0:ey, sx0:ex]
        dst = self.a[py + sy0:py + ey, px + sx0:px + ex]
        al = src[..., 3:]
        oa = al + dst[..., 3:] * (1 - al)
        rgb = src[..., :3] * al + dst[..., :3] * dst[..., 3:] * (1 - al)
        dst[..., :3] = np.where(oa > 1e-4, rgb / np.maximum(oa, 1e-4), 0)
        dst[..., 3:] = oa

    def cast(self, x0, x1, y0, y1, z):
        """Ground shadow of an axis-aligned box, as three nested layers (low/mid/full height) so the shadow is
        darkest at the wall foot and fades with distance. Parts are union-combined per layer (never doubled)."""
        sx, sy, _ = SHADOW
        from PIL import ImageDraw
        if not hasattr(self, 'layers'):
            self.layers = [np.zeros(self.a.shape[:2], np.float32) for _ in range(3)]
        pts = [(x0, y0), (x1, y0), (x1, y1), (x0, y1)]
        for i, f in enumerate((.3, .62, 1.0)):
            top = [(x + sx * z * f, y + sy * z * f) for x, y in pts]
            m = Image.new('L', (self.a.shape[1], self.a.shape[0]), 0)
            d = ImageDraw.Draw(m)
            for q in (pts, top, [pts[0], pts[1], top[1], top[0]], [pts[1], pts[2], top[2], top[1]],
                      [pts[2], pts[3], top[3], top[2]], [pts[3], pts[0], top[0], top[3]]):
                d.polygon([self.px(*p) for p in q], fill=255)
            self.layers[i] = np.maximum(self.layers[i], np.asarray(m, np.float32) / 255)

    def contact(self, x0, x1, y0, y1):
        from PIL import ImageDraw
        m = Image.new('L', (self.a.shape[1], self.a.shape[0]), 0)
        ImageDraw.Draw(m).rectangle([self.px(x0 - 1.5, y0 - 1.5), self.px(x1 + 1.5, y1 + 2.5)], fill=255)
        self.contact_mask = np.maximum(getattr(self, 'contact_mask', 0), np.asarray(m, np.float32) / 255)

    def finish(self, clip=None):
        """Put the blurred ground shadow under the artwork (clipped to the segment tile so runs never double up)."""
        acc = sum(self.layers) / 3 if hasattr(self, 'layers') else self.shadow
        sh = np.asarray(Image.fromarray((acc * 255).astype(np.uint8)).filter(ImageFilter.GaussianBlur(6)),
                        np.float32) / 255 * SHADOW[2]
        if hasattr(self, 'contact_mask'):
            cm = np.asarray(Image.fromarray((self.contact_mask * 255).astype(np.uint8)).filter(
                ImageFilter.GaussianBlur(3)), np.float32) / 255
            sh = np.maximum(sh, cm * .34)
        if clip:
            (gx0, gx1), (gy0, gy1) = clip
            # feathered clip: linear ramps over +-4 game px, complementary across tile seams, so adjacent
            # segments join without a dark/light line and isolated run ends fade instead of stopping square
            fe = 4
            gx = self.x0 + (np.arange(sh.shape[1]) + .5) / S
            gy = self.y0 + (np.arange(sh.shape[0]) + .5) / S
            mx = np.clip((gx - gx0 + fe) / (2 * fe), 0, 1) * np.clip((gx1 - gx + fe) / (2 * fe), 0, 1)
            my = np.clip((gy - gy0 + fe) / (2 * fe), 0, 1) * np.clip((gy1 - gy + fe) / (2 * fe), 0, 1)
            sh *= my[:, None] * mx[None, :]
        sh = np.minimum(sh, .40)                     # stays below the picking threshold (alpha 105/255)
        base = np.zeros_like(self.a)
        base[..., :3] = np.array([18, 22, 14], np.float32) / 255
        base[..., 3] = sh
        a = self.a
        oa = a[..., 3:] + base[..., 3:] * (1 - a[..., 3:])
        rgb = a[..., :3] * a[..., 3:] + base[..., :3] * base[..., 3:] * (1 - a[..., 3:])
        self.a = np.concatenate([np.where(oa > 1e-4, rgb / np.maximum(oa, 1e-4), 0), oa], 2)
        return self.a


def wrap_cols(tex, u0, u1):
    """Columns of a horizontally periodic texture (period = SEG game px) for tile coords u0..u1 (game px)."""
    idx = np.arange(int(round(u0 * S)), int(round(u1 * S)))
    return np.take(tex, idx, axis=1, mode='wrap')


def wrap_rows_rot(tex, v0, v1):
    """Periodic texture rotated 90 degrees: rows for run coords v0..v1 (texture u becomes screen y)."""
    cols = wrap_cols(tex, v0, v1)                    # (h, n)
    return np.transpose(cols, (1, 0, 2))[:, ::-1]   # (n, h)


def edge_shade(t, left=0, right=0, top=0, bottom=0, k=.72):
    """Ambient-occlusion style darkening along given edges (pixel widths)."""
    t = t.copy()
    h, w = t.shape[:2]
    m = np.ones((h, w), np.float32)
    if left:
        m[:, :left] *= np.linspace(k, 1, left)[None]
    if right:
        m[:, w - right:] *= np.linspace(1, k, right)[None]
    if top:
        m[:top] *= np.linspace(k, 1, top)[:, None]
    if bottom:
        m[h - bottom:] *= np.linspace(1, k, bottom)[:, None]
    t[..., :3] *= m[..., None]
    return t


def rect(tex, w, h):
    """Exactly w x h game px of a texture (tiled if needed)."""
    W, H = int(round(w * S)), int(round(h * S))
    ys = np.arange(H) % tex.shape[0]
    xs = np.arange(W) % tex.shape[1]
    return tex[ys][:, xs]


# ---------------------------------------------------------------- parts
def h_run(cv, T, x0, x1, tx=0):
    """Horizontal wall piece covering game x0..x1 (y -12..12). tx = segment centre for texture phase."""
    u0, u1 = x0 - tx + 48, x1 - tx + 48
    cv.cast(x0 - SHADOW[0] * Z_TOP, x1, -12, 12, Z_TOP - 4)
    cv.contact(x0 - 8, x1 + 8, -12, 12)
    # back parapet (inner face visible) with merlons
    cv.blit(wrap_cols(T['TOP'], u0, u1)[:PAR * S], x0, -12 - Z_SILL)                  # parapet top
    inner = edge_shade(wrap_cols(T['WALK'], u0, u1)[:(Z_SILL - Z_WALK) * S], bottom=4, k=.6)
    cv.blit(inner, x0, -12 + PAR - Z_SILL, .78)
    for c in merlon_centres(x0, x1, tx):
        a, b = max(x0, c - MER / 2), min(x1, c + MER / 2)
        cv.blit(rect(T['TOP'], b - a, PAR), a, -12 - Z_TOP, 1.0)
        cv.blit(edge_shade(rect(T['MERF'], b - a, Z_TOP - Z_SILL), left=3, k=.7), a, -12 + PAR - Z_TOP, .9)
    # walkway
    walk = wrap_cols(T['WALK'], u0, u1)[:(24 - 2 * PAR) * S]
    cv.blit(edge_shade(walk, top=5, k=.55), x0, -12 + PAR - Z_WALK, .92)
    # front parapet top in the embrasures, then the face (with front merlons)
    cv.blit(wrap_cols(T['TOP'], u0, u1)[:PAR * S], x0, 12 - PAR - Z_SILL)
    cv.blit(wrap_cols(T['FACE'], u0, u1), x0, 12 - Z_TOP)


def merlon_centres(a0, a1, t):
    out = []
    k = int(np.floor((a0 - t - 16 - MER) / 32))
    while True:
        c = t + 16 + 32 * k
        if c - MER / 2 >= a1:
            break
        if c + MER / 2 > a0:
            out.append(c)
        k += 1
    return out


def v_run(cv, T, y0, y1, ty=0, end_face=True):
    """Vertical wall piece covering game y0..y1 (x -12..12). ty = segment centre for texture phase."""
    cv.cast(-12, 12, y0 - SHADOW[1] * Z_TOP - 2, y1, Z_TOP - 4)
    cv.contact(-12, 12, y0 - 8, y1 + 8)
    v0, v1 = y0 - ty + 48, y1 - ty + 48
    walk = wrap_rows_rot(T['WALK'], v0, v1)                          # (len, depth)
    walk = walk[:, :(24 - 2 * PAR) * S]
    cv.blit(edge_shade(walk, left=5, right=5, k=.5), -12 + PAR, y0 - Z_WALK, .8)
    top = wrap_rows_rot(T['TOP'], v0, v1)[:, :PAR * S]
    for x in (-12, 12 - PAR):
        cv.blit(edge_shade(top, left=2 if x < 0 else 0, right=0 if x < 0 else 2, k=.55), x, y0 - Z_SILL, 1.06)
    for c in merlon_centres(y0, y1, ty):
        a, b = max(y0, c - MER / 2), min(y1, c + MER / 2)
        for x in (-12, 12 - PAR):
            cv.blit(rect(T['TOP'], PAR, b - a), x, a - Z_TOP, 1.04)
            face = edge_shade(rect(T['MERF'], PAR, Z_TOP - Z_SILL), left=2 if x < 0 else 0, right=0 if x < 0 else 2)
            if b == y1 and end_face:
                continue                                              # the end face below shows this section
            cv.blit(face, x, b - Z_TOP, .86)
    if end_face:
        # cross-section at the south end: a face slice centred on an embrasure (merlon halves at both edges)
        sl = wrap_cols(T['FACE'], 4, 28).copy()
        r0 = (Z_TOP - Z_WALK) * S
        sl[:r0, PAR * S:(24 - PAR) * S, 3] = 0                        # walkway level between the parapets
        sl = edge_shade(sl, left=3, right=3, k=.8)
        cv.blit(sl, -12, y1 - Z_TOP)


def tower(cv, T, cx=0, cy=0, banner=None):
    """30 x 30 junction / gate tower centred on (cx, cy)."""
    x0, x1, y0, y1 = cx - 15, cx + 15, cy - 15, cy + 15
    cv.cast(x0, x1, y0, y1, T_TOP - 4)
    cv.contact(x0, x1, y0, y1)
    rise = T_WALK - Z_WALK
    cv.blit(rect(T['WALK'], 20, 20), x0 + PAR, y0 + PAR - T_WALK, .9)                        # floor
    cv.blit(rect(T['TOP'], 30, PAR), x0, y0 - T_SILL)                                          # back parapet top
    cv.blit(edge_shade(rect(T['WALK'], 20, T_SILL - T_WALK), bottom=4, k=.6), x0 + PAR, y0 + PAR - T_SILL, .75)
    for x in (x0, x1 - PAR):
        cv.blit(rect(T['TOP'], PAR, 30), x, y0 - T_SILL)                                       # side parapet tops
    for x in (x0, x1 - 8):                                                                     # back corner merlons
        cv.blit(rect(T['TOP'], 8, 8), x, y0 - T_TOP, 1.04)
        cv.blit(edge_shade(rect(T['MERF'], 8, T_TOP - T_SILL), left=2, k=.7), x, y0 + 8 - T_TOP, .86)
    for x in (x0, x1 - 8):                                                                     # side merlon tops
        cv.blit(rect(T['TOP'], 8, 8), x, y1 - 8 - T_TOP, 1.04)
    cv.blit(rect(T['TOP'], 30, PAR), x0, y1 - PAR - T_SILL)                                   # front parapet top
    face = wrap_cols(T['FACE'], 1, 31)
    plinth = face[-rise * S:]
    full = np.concatenate([face, plinth], 0)
    full = edge_shade(full, left=4, right=3, k=.7)
    full = grade(full, .96)
    cv.blit(full, x0, y1 - T_TOP)
    if banner is not None:
        cv.blit(banner, cx - banner.shape[1] / S / 2, y1 - T_TOP + 24)


def banner_tex(T, w):
    b = T['BANNER']
    h = int(round(b.shape[0] * w * S / b.shape[1]))
    return sharpen(resize(b, int(w * S), h), .3)


# ---------------------------------------------------------------- modules
def module_h(T, n=False, s=False):
    cv = Canvas()
    if n:
        v_run(cv, T, -48, -15, ty=-96 + 0)
    h_run(cv, T, -48, 48)
    if n or s:
        tower(cv, T)
    if s:
        v_run(cv, T, 15, 48, ty=96 - 96)
    return cv.finish(((-48, 48), (-48, 48)))


def module_v(T, e=False, w=False):
    cv = Canvas()
    if e or w:
        v_run(cv, T, -48, -15, end_face=False)
        if w:
            h_run(cv, T, -48, -15)
        if e:
            h_run(cv, T, 15, 48)
        tower(cv, T)
        v_run(cv, T, 15, 48)
    else:
        v_run(cv, T, -48, 48)
    return cv.finish(((-48, 48), (-48, 48)))


def module_gate_h(T, G, state):
    cv = Canvas()
    cv.cast(-48, 48, -14, 14, G_TOP - 4)
    cv.contact(-48, 48, -14, 14)
    cv.blit(rect(T['TOP'], 96, PAR), -48, -14 - G_SILL)
    cv.blit(edge_shade(rect(T['WALK'], 96, G_SILL - G_WALK), bottom=4, k=.6), -48, -14 + PAR - G_SILL, .78)
    for c in merlon_centres(-48, 48, 0):
        a, b = max(-48, c - MER / 2), min(48, c + MER / 2)
        cv.blit(rect(T['TOP'], b - a, PAR), a, -14 - G_TOP)
        cv.blit(edge_shade(rect(T['MERF'], b - a, G_TOP - G_SILL), left=3, k=.7), a, -14 + PAR - G_TOP, .9)
    cv.blit(edge_shade(rect(T['WALK'], 96, 28 - 2 * PAR), top=5, k=.55), -48, -14 + PAR - G_WALK, .92)
    cv.blit(rect(T['TOP'], 96, PAR), -48, 14 - PAR - G_SILL)
    face = G['GATE1' if state else 'GATE0']
    hg = face.shape[0] / S
    face = edge_shade(face, left=4, right=4, k=.75)
    cv.blit(face, -48, 14 - hg)
    ban = banner_tex(T, 14)
    by = 14 - hg + 11
    cv.blit(ban, -ban.shape[1] / S / 2 + 1, by)
    out = cv.finish(((-48, 48), (-48, 48)))
    bb = (-ban.shape[1] / S / 2 + 1, by, ban.shape[1] / S, ban.shape[0] / S)
    return out, bb


def module_gate_v(T, G, state):
    cv = Canvas()
    ban = banner_tex(T, 16)
    tower(cv, T, 0, -33)
    if state:
        l = G['LEAF_L']
        cv.blit(l, -12 - l.shape[1] / S, -17 - l.shape[0] / S, .9)
    cv.cast(-12, 12, -18, 18, Z_TOP - 4)
    v_run(cv, T, -18, 18, ty=0, end_face=False)
    tower(cv, T, 0, 33, banner=ban)
    if state:
        r = G['LEAF_R']
        cv.blit(r, 13, 19 - r.shape[0] / S, .95)
    out = cv.finish(((-48, 48), (-48, 50)))
    bb = (-ban.shape[1] / S / 2, 48 - T_TOP + 24, ban.shape[1] / S, ban.shape[0] / S)
    return out, bb


def trim(a, cv_x0=-72, cv_y0=-200):
    al = a[..., 3]
    al[al < 2 / 255] = 0
    ys, xs = np.nonzero(al > 0)
    y0, y1, x0, x1 = ys.min(), ys.max() + 1, xs.min(), xs.max() + 1
    ox, oy = -cv_x0 * S - x0, -cv_y0 * S - y0          # sprite-pixel position of the game origin
    return a[y0:y1, x0:x1], ox, oy


def main():
    T = build_textures()
    G = gate_textures(T)
    mods = {}
    for key, n, s in (('h', 0, 0), ('hN', 1, 0), ('hS', 0, 1), ('hNS', 1, 1)):
        mods[key] = (module_h(T, n, s), None)
    for key, e, w in (('v', 0, 0), ('vE', 1, 0), ('vW', 0, 1), ('vEW', 1, 1)):
        mods[key] = (module_v(T, e, w), None)
    for st in (0, 1):
        mods['g%d' % st] = module_gate_h(T, G, st)
        mods['gv%d' % st] = module_gate_v(T, G, st)
    # pack: one row per family, 4 px transparent gutters
    order = [['h', 'hN', 'hS', 'hNS', 'g0', 'g1'], ['v', 'vE', 'vW', 'vEW', 'gv0', 'gv1']]
    trimmed = {k: trim(v[0]) for k, v in mods.items()}
    gut = 4
    W = max(sum(trimmed[k][0].shape[1] + gut for k in row) + gut for row in order)
    H = sum(max(trimmed[k][0].shape[0] for k in row) + gut for row in order) + gut
    sheet = np.zeros((H, W, 4), np.float32)
    meta = {'scale': S, 'source': 'scripts/art/build_walls.py', 'sprites': {}}
    y = gut
    for row in order:
        x = gut
        for k in row:
            a, ox, oy = trimmed[k]
            h, w = a.shape[:2]
            sheet[y:y + h, x:x + w] = a
            m = {'x': x, 'y': y, 'w': w, 'h': h, 'ox': int(ox), 'oy': int(oy)}
            if mods[k][1]:
                bx, by, bw, bh = mods[k][1]
                m['cloth'] = [int(x + ox + bx * S) - 1, int(y + oy + by * S) - 1, int(bw * S) + 2, int(bh * S) + 2]
            meta['sprites'][k] = m
            x += w + gut
        y += max(trimmed[k][0].shape[0] for k in row) + gut
    out = (np.clip(sheet, 0, 1) * 255 + .5).astype(np.uint8)
    out[out[..., 3] == 0, :3] = 0                               # fully transparent pixels carry no colour
    Image.fromarray(out, 'RGBA').save(os.path.join(ASSETS, 'walls-v1.png'), optimize=True)
    with open(os.path.join(ASSETS, 'walls-v1.json'), 'w') as f:
        json.dump(meta, f, separators=(',', ':'))
    print('wrote walls-v1.png', out.shape[1], 'x', out.shape[0], 'and walls-v1.json with', len(meta['sprites']), 'sprites')


if __name__ == '__main__':
    main()
